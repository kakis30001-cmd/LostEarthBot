def emoji(emoji_id: str, fallback: str = "") -> str:
    """Возвращает премиум эмодзи Telegram"""
    return f'<tg-emoji emoji-id="{emoji_id}">{fallback}</tg-emoji>'

def random_enderia_emoji(only_cats: bool = False):
    """Случайный эмодзи Эндерии"""
    import random
    if only_cats:
        cat_emojis = [
            ENDERIA_EMOJI["cat_dance"],
            ENDERIA_EMOJI["cat_ok"],
            ENDERIA_EMOJI["cat_up"],
            ENDERIA_EMOJI["cat_laugh"],
            ENDERIA_EMOJI["cat_kiss"],
            ENDERIA_EMOJI["cat_think"],
        ]
        return emoji(random.choice(cat_emojis), "🐱")
    
    all_emojis = list(ENDERIA_EMOJI.values())
    return emoji(random.choice(all_emojis), "✨")

def get_enderia_emojis(count: int = 2, only_cats: bool = False):
    """Возвращает несколько случайных эмодзи"""
    import random
    emojis = []
    for _ in range(count):
        emojis.append(random_enderia_emoji(only_cats))
    return " ".join(emojis)

